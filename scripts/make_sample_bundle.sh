#!/usr/bin/env bash
# Build app/src/sample/sample_runs.js: REAL JUnit reports from running the demo-shop suite RUNS_PER_COMMIT times
# on each commit of its scripted history (same loop as demo_ci.sh, but saved instead of uploaded).
# The app bundles this file so a judge or new user can press "Load sample data" and see FlakeLens work at once.
# Usage: make_sample_bundle.sh [runs-per-commit]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
per=${1:-4}
out="$here/../app/src/sample/sample_runs.js"; mkdir -p "$(dirname "$out")"
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
repo="$work/repo"; "$here/make_demo_history.sh" "$repo" >/dev/null
n=0; : > "$work/list.tsv"
for c in $(git -C "$repo" rev-list --reverse HEAD); do
  git -C "$repo" worktree add -q --detach "$work/$c" "$c"
  for i in $(seq 1 "$per"); do
    n=$((n+1)); x="$work/run-$n.xml"
    (cd "$work/$c" && node --test --test-reporter=junit --test-reporter-destination="$x" 'test/*.test.js' >/dev/null 2>&1) || true
    sed -i "s|$work/$c/||g" "$x"  # keep paths repo-relative (no temp dirs in the bundle)
    echo "run $n commit ${c:0:8}: $(grep -c '<failure' "$x") failing" >&2
    printf 'ci-%s\t%s\t%s\n' "$n" "$c" "$x" >> "$work/list.tsv"
  done
  git -C "$repo" worktree remove --force "$work/$c"
done
node -e '
const fs = require("fs");
const rows = fs.readFileSync(process.argv[1], "utf8").trim().split("\n").map((l) => l.split("\t"));
const runs = rows.map(([runId, commit, file]) => ({ runId, commit, branch: "main", xml: fs.readFileSync(file, "utf8") }));
fs.writeFileSync(process.argv[2], "// Generated by scripts/make_sample_bundle.sh from real demo-shop test runs. Do not edit.\nexport default " + JSON.stringify({ generated: new Date().toISOString(), source: "scripts/make_sample_bundle.sh", runs }, null, 1) + ";\n");
' "$work/list.tsv" "$out"
echo "wrote $out ($n runs)" >&2
